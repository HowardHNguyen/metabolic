import { MODEL_SPEC } from "./localModel.js";
import jsPDF from "jspdf";
import html2canvas from "html2canvas";

export async function exportRiskOverTimeToPDF(contentRef, userEmail) {
  if (!contentRef.current) {
    console.error("Content ref not attached");
    return;
  }
  try {
    const canvas = await html2canvas(contentRef.current, {
      scale: 2,
      useCORS: true,
      backgroundColor: "#f6faf9",
      logging: false,
    });

    const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "letter" });
    const pdfWidth = pdf.internal.pageSize.getWidth();
    const pdfHeight = pdf.internal.pageSize.getHeight();
    const margin = 12;
    const contentWidth = pdfWidth - margin * 2;
    const headerHeight = 18;
    const footerHeight = 14;
    const contentHeight = pdfHeight - margin * 2 - headerHeight - footerHeight;
    const imgWidth = contentWidth;
    const imgHeight = (canvas.height * imgWidth) / canvas.width;

    const today = new Date();
    const dateStr = today.toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" });
    const fileDate = today.toISOString().split("T")[0];

    function drawHeader() {
      pdf.setFont("helvetica", "bold");
      pdf.setFontSize(14);
      pdf.setTextColor(89, 24, 150);
      pdf.text("vitalCKM Metabolic Screen", margin, margin + 6);
      pdf.setFont("helvetica", "normal");
      pdf.setFontSize(10);
      pdf.setTextColor(89, 89, 89);
      pdf.text("Metabolic Health Progress Report", margin, margin + 11);
      pdf.setFontSize(8);
      pdf.text(dateStr, pdfWidth - margin, margin + 6, { align: "right" });
      if (userEmail) pdf.text(userEmail, pdfWidth - margin, margin + 11, { align: "right" });
      pdf.setDrawColor(220, 220, 220);
      pdf.setLineWidth(0.2);
      pdf.line(margin, margin + 14, pdfWidth - margin, margin + 14);
    }

    function drawFooter(pageNum, totalPages) {
      const footerY = pdfHeight - margin - 8;
      pdf.setDrawColor(220, 220, 220);
      pdf.setLineWidth(0.2);
      pdf.line(margin, footerY - 6, pdfWidth - margin, footerY - 6);

      pdf.setFont("helvetica", "italic");
      pdf.setFontSize(7);
      pdf.setTextColor(120, 120, 120);
      pdf.text(
        "Educational tool. Discuss results with your clinician. Quick Screen = estimated chance of metabolic syndrome now (NHANES-trained model).",
        margin, footerY - 2
      );
      pdf.setFont("helvetica", "normal");
      pdf.text(`Generated by vitalCKM · Model v${MODEL_SPEC.version} · Page ${pageNum} of ${totalPages}`, margin, footerY + 3);
    }

    if (imgHeight <= contentHeight) {
      drawHeader();
      pdf.addImage(canvas.toDataURL("image/png"), "PNG", margin, margin + headerHeight, imgWidth, imgHeight);
      drawFooter(1, 1);
    } else {
      const totalPages = Math.ceil(imgHeight / contentHeight);
      const sliceHeight = (contentHeight / imgHeight) * canvas.height;
      for (let pageNum = 1; pageNum <= totalPages; pageNum++) {
        if (pageNum > 1) pdf.addPage();
        drawHeader();
        const pageCanvas = document.createElement("canvas");
        pageCanvas.width = canvas.width;
        pageCanvas.height = Math.min(sliceHeight, canvas.height - (pageNum - 1) * sliceHeight);
        const ctx = pageCanvas.getContext("2d");
        ctx.drawImage(canvas, 0, (pageNum - 1) * sliceHeight, canvas.width, pageCanvas.height, 0, 0, canvas.width, pageCanvas.height);
        const pageImgHeight = (pageCanvas.height * imgWidth) / canvas.width;
        pdf.addImage(pageCanvas.toDataURL("image/png"), "PNG", margin, margin + headerHeight, imgWidth, pageImgHeight);
        drawFooter(pageNum, totalPages);
      }
    }
    pdf.save(`vitalCKM-Metabolic-Report-${fileDate}.pdf`);
  } catch (error) {
    console.error("PDF export failed:", error);
    alert("PDF export failed. Please try again.");
  }
}
